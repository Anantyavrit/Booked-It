// Helper: standard screen templates
const createScreens = (types = ['2D', '2D', 'IMAX']) => {
  const layouts = [
    { rows: 10, seatsPerRow: 16, format: '2D', tier: { premiumRows: 2, premiumMultiplier: 1.25 } },
    { rows: 8,  seatsPerRow: 14, format: '2D', tier: { premiumRows: 2, premiumMultiplier: 1.2 } },
    { rows: 12, seatsPerRow: 22, format: '3D', tier: { premiumRows: 3, premiumMultiplier: 1.3 } },
    { rows: 14, seatsPerRow: 24, format: 'IMAX', tier: { premiumRows: 4, premiumMultiplier: 1.4 } },
    { rows: 8,  seatsPerRow: 12, format: '4DX', tier: { premiumRows: 1, premiumMultiplier: 1.5 } },
  ];

  return types.map((format, idx) => {
    const layout = layouts.find((l) => l.format === format) || layouts[idx % layouts.length];
    return {
      name: `Screen ${idx + 1}`,
      rows: layout.rows,
      seatsPerRow: layout.seatsPerRow,
      format,
      tier: layout.tier,
    };
  });
};

