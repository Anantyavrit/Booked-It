export const seedTheatres = async () => {
  const mongoUri = process.env.MONGO_URI;
  if (!mongoUri) {
    throw new Error('MONGO_URI is not set in environment.');
  }

  await mongoose.connect(mongoUri);
  console.log('[seedTheatres] Connected to MongoDB:', mongoose.connection.name);

  let insertedCount = 0;
  let updatedCount = 0;

  for (const t of THEATRES_DATA) {
    const filter = {
      name: t.name,
      city: t.city,
      area: t.area,
    };

    const res = await Theatre.updateOne(filter, { $set: t }, { upsert: true });
    if (res.upsertedCount > 0) {
      insertedCount++;
    } else if (res.modifiedCount > 0 || res.matchedCount > 0) {
      updatedCount++;
    }
  }

  const totalTheatres = await Theatre.countDocuments({ isActive: true });
  const distinctCities = await Theatre.distinct('city', { isActive: true });

  console.log('───────────────────────────────────────────────────────');
  console.log('[seedTheatres] Seeding Summary:');
  console.log(`  • Inserted (new)       : ${insertedCount}`);
  console.log(`  • Updated (existing)   : ${updatedCount}`);
  console.log(`  • Total Active Theatres: ${totalTheatres}`);
  console.log(`  • Covered Cities (${distinctCities.length}): ${distinctCities.join(', ')}`);
  console.log('───────────────────────────────────────────────────────');

  await mongoose.disconnect();
  console.log('[seedTheatres] Disconnected from MongoDB. Done.');
};

// Direct invocation check
const isDirectRun = process.argv[1] && process.argv[1].endsWith('seedTheatres.js');
if (isDirectRun) {
  seedTheatres()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error('[seedTheatres] Error:', err);
      process.exit(1);
    });
}
